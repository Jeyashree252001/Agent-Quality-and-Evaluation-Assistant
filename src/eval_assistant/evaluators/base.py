from abc import ABC, abstractmethod
from ..models import TestCase, TargetAgentResponse, CheckResult


class BaseEvaluator(ABC):
    """Abstract interface for all evaluation components."""

    @property
    @abstractmethod
    def name(self) -> str:
        """Name of the evaluator."""
        pass

    @abstractmethod
    def evaluate(self, test_case: TestCase, response: TargetAgentResponse) -> CheckResult:
        """
        Evaluate a single test case against the agent response.
        
        Args:
            test_case: Test case definition and expected constraints.
            response: Output generated by the target agent.
            
        Returns:
            CheckResult with pass/fail, score, evidence, and suggested improvement.
        """
        pass
